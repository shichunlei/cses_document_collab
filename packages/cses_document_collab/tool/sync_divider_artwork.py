"""Extract existing BlockCraft SVG masks and tape gradients for Flutter.

Run: python3 tool/sync_divider_artwork.py /path/to/@ccc/blockcraft
The tool writes only divider artwork; it does not modify dependencies or schemas.
Source shapes and gradients remain attributable to @ccc/blockcraft 0.11.14.
"""
import json
import re
import sys
from pathlib import Path
from urllib.parse import unquote

source = Path(sys.argv[1]) / 'themes' / 'blocks'
output = Path(__file__).resolve().parents[1] / 'lib' / 'src' / 'editor' / 'collab_divider_artwork.dart'
svg = dict((name, unquote(value)) for name, value in re.findall(
    r'\$_(\w+): url\("data:image/svg\+xml,([^"\n]+)"\);',
    (source / '_divider-patterns.scss').read_text()))
scss = (source / 'divider-block.scss').read_text()
tapes = {}
for name, expression in re.findall(r'&\.(tape-[\w-]+) \{\s*background-image: (.*?);', scss):
    layers = []
    # Nested rgb()/hsl() commas are kept inside each color.
    for repeat, angle, rest in re.findall(r'(repeating-)?linear-gradient\(([-\d.]+)deg, (.*?)(?=\), (?:repeating-)?linear-gradient|\);?$|\)$)', expression):
        stops = []
        for color, position, unit in re.findall(r'((?:rgba?|hsla?)\([^)]+\)|#[\da-fA-F]+|transparent)(?:\s+([\d.]+)(px|%))?', rest):
            if color.startswith('rgb'):
                c = [float(v.strip()) for v in color[color.index('(')+1:-1].split(',')]
                rgb = list(map(round, c[:3])); alpha = c[3] if len(c) > 3 else 1
            elif color.startswith('hsl'):
                import colorsys
                c = [v.strip().strip('%') for v in color[color.index('(')+1:-1].split(',')]
                h, sat, light = map(float, c[:3])
                rgb = [round(v * 255) for v in colorsys.hls_to_rgb(h/360, light/100, sat/100)]
                alpha = float(c[3]) if len(c)>3 else 1
            elif color == 'transparent': rgb = [0, 0, 0]; alpha = 0
            else: rgb = [int(color[i:i+2],16) for i in (1,3,5)]; alpha = 1
            stops.append({'color': (round(alpha*255)<<24) | (rgb[0]<<16) | (rgb[1]<<8) | rgb[2], 'position': float(position) if position else None})
        assert stops, (name, rest)
        layers.append({'angle': float(angle), 'repeat': bool(repeat), 'pixels': 'px' in rest, 'stops': stops})
    assert layers, name
    tapes[name] = layers
assert len(svg)==9 and len(tapes)==5
output.write_text('// Generated by tool/sync_divider_artwork.py from @ccc/blockcraft 0.11.14.\n'
                  '// Source: themes/blocks/_divider-patterns.scss and divider-block.scss.\n'
                  '// Preserve upstream attribution when updating these vector masks/gradients.\n'
                  'const dividerSvgMasks = <String, String>{\n' +
                  ''.join(f'  {json.dumps(k)}: {json.dumps(v)},\n' for k,v in svg.items()) + '} ;\n' +
                  'const dividerTapeLayers = <String, List<Map<String, Object?>>>{\n' +
                  ''.join(f'  {json.dumps(k)}: {json.dumps(v)},\n' for k,v in tapes.items()) + '};\n')
print(f'Extracted {len(svg)} SVG masks, {sum(map(len,tapes.values()))} gradient layers')
import subprocess
subprocess.run(['dart', 'format', str(output)], check=True)
