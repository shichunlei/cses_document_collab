const source = 'fesm2022/ccc-blockcraft-framework-block-std-typography.mjs';
const modulePath = path.join(root, source);
const upstream = await import(pathToFileURL(modulePath));

/** Resolve actual CSS pixels using the release's paragraph and inline readers. */
function fontSize(props, attrs = {}) {
  const paragraph = upstream.resolveEditableBlockFontSize(props, 'paragraph', 16);
  const {pixels, scale} = upstream.readInlineFontSize(attrs);
  const paragraphScale = upstream.normalizeParagraphFontScale(props.pfs) ?? 1;
  return (pixels === null ? paragraph : pixels * paragraphScale) * scale;
}

