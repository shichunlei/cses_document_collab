/// Real-device acceptance uses an isolated SQLite file and desktop-generated
/// updates. It does not log in, clear app data or change an online document.
void main() {
  IntegrationTestWidgetsFlutterBinding.ensureInitialized();
  testWidgets('phone block locks: UI toggle, IME, inheritance, history and persistence', (tester) async {
    final directory = await Directory.systemTemp.createTemp('device-block-lock-');
    final gateway = _DevicePeer();
    final controller = CollabController.cses(
      config: CollabDocumentConfig(
        documentId: 'fixture-doc',
        serverIdentity: 'wss://isolated.test/ws',
        companyId: 'test',
        userId: 'desktop-user',
        databasePath: '${directory.path}/cache.sqlite',
        editable: true,
      ),
      gateway: gateway,
    );
    try {
      await controller.initialize();
      gateway.sync(base64Decode(_desktopFixture));
      await tester.pumpWidget(MaterialApp(home: CollaborativeEditorPage(collab: controller)));
      await tester.pumpAndSettle();
      expect(controller.canEdit, isTrue);
      expect(controller.blockLock('p1').locked, isTrue);
      expect(controller.blockLock('child').sourceId, 'callout');
      final editor = controller.editorState;
      final first = editor.document.root.children.first;
      final second = editor.document.root.children[1];
      await tester.tap(find.text('桌面定稿', findRichText: true).first);
      await tester.pumpAndSettle();
      expect(editor.canInputAt(editor.selection), isFalse);
      await tester.tap(find.byKey(const ValueKey('block-lock-menu-trigger-p1')));
      await tester.pumpAndSettle();
      expect(find.text('锁定内容块'), findsOneWidget);
      await tester.tap(find.byKey(const ValueKey('block-lock-p1')));
      await tester.pumpAndSettle();
      expect(controller.blockLock('p1').locked, isFalse);
      await tester.tap(find.text('桌面定稿', findRichText: true).first);
      await tester.pumpAndSettle();
      expect(editor.canInputAt(editor.selection), isTrue);
      tester.testTextInput.enterText('手机解锁后中文输入');
      await tester.pumpAndSettle();
      expect(first.delta!.toPlainText(), contains('手机解锁后中文输入'));
      await controller.setBlockLocked('p1', true);
      await tester.pumpAndSettle();
      final text = first.delta!.toPlainText();
      final history = editor.undoManager.undoStack.last;
      editor.undoManager.undo();
      await tester.pumpAndSettle();
      expect(first.delta!.toPlainText(), text);
      expect(identical(history, editor.undoManager.undoStack.last), isTrue);
      await editor.apply(editor.transaction..insertText(second, 0, '其他块仍可编辑'));
      await tester.pumpAndSettle();
      expect(second.delta!.toPlainText(), startsWith('其他块仍可编辑'));
      await tester.tap(find.byKey(const ValueKey('block-lock-menu-trigger-child')));
      await tester.pumpAndSettle();
      expect(find.text('由上级内容块锁定'), findsOneWidget);
      expect(tester.widget<SwitchListTile>(find.byKey(const ValueKey('block-lock-child'))).onChanged, isNull);
      await tester.tap(find.byTooltip('关闭').last);
      await tester.pumpAndSettle();
      expect(gateway.updates, greaterThan(0));
      await tester.pumpWidget(const SizedBox());
      await tester.pumpAndSettle();
      await controller.close();
      final reopened = CollabController.cses(
        config: CollabDocumentConfig(
          documentId: 'fixture-doc',
          serverIdentity: 'wss://isolated.test/ws',
          companyId: 'test',
          userId: 'desktop-user',
          databasePath: '${directory.path}/cache.sqlite',
          editable: true,
        ),
        gateway: gateway,
      );
      try {
        await reopened.initialize();
        expect(reopened.blockLock('p1').locked, isTrue);
        expect(reopened.editorState.document.root.children.first.delta!.toPlainText(), text);
      } finally {
        await reopened.close();
      }
    } finally {
      await tester.pumpWidget(const SizedBox());
      await controller.close();
      await gateway.close();
      await directory.delete(recursive: true);
    }
  });
}

