/// Owns a fake transport event stream; all actual CRDT and UI code stays production.
class _DevicePeer implements CsesCollabGateway {
  final events = StreamController<bool>.broadcast();
  Map<String, void Function(Map<String, dynamic>)> callbacks = {};
  int updates = 0;

  /// The isolated peer is always connected.
  @override
  bool get isConnected => true;

  /// Borrowed subscription, closed after the controller.
  @override
  Stream<bool> get connectionStates => events.stream;

  /// Register routing [callbacks] for [pageId], [documentId], [instanceId].
  @override
  Future<void> register({
    required String pageId,
    required String documentId,
    required String instanceId,
    required Map<String, void Function(Map<String, dynamic>)> callbacks,
  }) async {
    this.callbacks = callbacks;
  }

  /// Record [action] updates for [pageId] and [body] without accessing a server.
  @override
  bool send(String pageId, String action, Map<String, dynamic> body) {
    if (action == 'collabUpdate') updates++;
    return true;
  }

  /// Remove the borrowed [pageId] route.
  @override
  Future<void> unregister(String pageId) async {
    callbacks = {};
  }

  /// Release the owned stream after the controller has unsubscribed.
  Future<void> close() => events.close();

  /// Deliver formal desktop [bytes] using the real session callback.
  void sync(List<int> bytes) => callbacks['collabSync']!({
    'data': base64Encode(bytes),
    'stateVector': base64Encode([0]),
  });
}
